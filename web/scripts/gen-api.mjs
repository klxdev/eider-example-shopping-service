// Generates the typed API client's types from the Eider server's OpenAPI description.
//
//   node scripts/gen-api.mjs      (npm run gen; scripts/build.sh runs it)
//
// The server prints its description with `--openapi` (the same document it serves at
// /openapi.json, built from the operations its routes are registered with), so there is no
// port to start or wait for. openapi-typescript turns it into src/api/schema.d.ts, which
// src/api/client.ts gives to openapi-fetch.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const server = process.env.SHOP_SERVER_BIN ?? join(web, "..", "server", "target", "server");
if (!existsSync(server)) {
  console.error(`gen-api: ${server} is missing; build it first (sh scripts/build.sh)`);
  process.exit(2);
}
const text = execFileSync(server, ["--openapi"], { encoding: "utf8" });
const doc = JSON.parse(text);
const out = join(web, "src", "api");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "openapi.json"), JSON.stringify(doc, null, 2) + "\n");
const ast = await openapiTS(doc);
writeFileSync(
  join(out, "schema.d.ts"),
  "// Generated by scripts/gen-api.mjs from the Eider server's --openapi output. Do not edit.\n" + astToString(ast),
);
console.log(`gen-api: ${Object.keys(doc.paths).length} paths -> src/api/schema.d.ts`);
